// Runs every experiment and writes docs/backtest/results-<label>.json and docs/backtest/tables-<label>.md.
// Usage: NODE_USE_ENV_PROXY=1 node backtest/run.mjs [label] [--fetch]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as D from './data.mjs';
import * as A from './experiments-a.mjs';
import * as B from './experiments-b.mjs';
import { fetchAll } from './fetch.mjs';
import { newsEval } from './news-eval.mjs';

const args = process.argv.slice(2);
const label = args.find((a) => !a.startsWith('--')) || 'current';
if (args.includes('--fetch')) await fetchAll();

const ORDER = [A.e1, A.e2, A.e3, A.e4, A.e5, A.e6, B.e7, B.e8, B.e9, A.e10, B.e11, B.e12, B.e13, B.e14, A.e14b, B.e15, A.e16, A.e17, A.e18, B.e19, newsEval];
const out = { label, generated: new Date().toISOString().slice(0, 10), seasons: D.SEASONS, train: D.TRAIN, test: D.TEST, coverage: {}, experiments: {} };
for (const s of D.SEASONS) {
  const S = D.loadSeason(s);
  out.coverage[s] = { weeks: S.lastWeek, injuryRows: S.injMatch.total, injuryUnmatched: S.injMatch.unmatched };
}
let md = `# Backtest tables (${label})\n\nGenerated ${out.generated} by \`npm run backtest\`. Seasons ${D.SEASONS[0]}-${D.SEASONS[D.SEASONS.length - 1]}; constants are fitted on ${D.TRAIN.join(', ')} and judged on ${D.TEST.join(', ')}.\n`;
for (const fn of ORDER) {
  const t = Date.now();
  const r = fn();
  out.experiments[r.id] = { title: r.title, findings: r.findings, fit: r.fit, tables: r.tables };
  md += `\n## ${r.id}. ${r.title}\n\n${r.findings.map((f) => `- ${f}`).join('\n')}\n`;
  for (const tb of r.tables) {
    md += `\n${tb.caption}\n\n| ${tb.head.join(' | ')} |\n| ${tb.head.map(() => '---').join(' | ')} |\n${tb.rows.map((row) => `| ${row.map((c) => (c == null ? '' : c)).join(' | ')} |`).join('\n')}\n`;
  }
  console.log(`${r.id} done in ${Date.now() - t} ms`);
}
const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'docs', 'backtest');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, `results-${label}.json`), JSON.stringify(out, null, 1));
fs.writeFileSync(path.join(dir, `tables-${label}.md`), md);
console.log(`wrote docs/backtest/results-${label}.json and tables-${label}.md`);

// The Track record page reads a compact summary, with the engine's earlier numbers beside the current ones.
if (label === 'current') {
  const E = out.experiments;
  const beforeFile = path.join(dir, 'results-before.json');
  const B = fs.existsSync(beforeFile) ? JSON.parse(fs.readFileSync(beforeFile, 'utf8')).experiments : null;
  const site = 'Site value today (values.js)';
  const pick = (e) => ({
    ripple: { byKind: e.E5.fit.byKind, byConf: e.E5.fit.byConf },
    values: Object.fromEntries(['QB', 'RB', 'WR', 'TE'].map((pos) => [pos, e.E11.fit[pos][site]])),
    winBrier: e.E7.fit.pooledBrier,
    lineup: e.E8.fit,
    trades: { n: e.E13.fit.n, decided: e.E13.fit.decided, agree: e.E13.fit.agree },
  });
  const track = {
    generated: out.generated,
    seasons: out.seasons,
    startSit: Object.fromEntries(Object.entries(E.E2.fit).map(([k, v]) => [k, v.test.filter((b) => b.n >= 150)])),
    tiebreak: E.E3.fit,
    tags: { status: E.E4.fit.status, byPractice: E.E4.fit.questionableByPractice, byPosition: E.E4.fit.questionableByPosition, vsProjection: E.E4.fit.projRatioTest },
    matchup: E.E6.fit['Raw points allowed, last 6 weeks (site today)'],
    winTables: { site: E.E7.tables[1].rows, lineups: E.E7.tables[2].rows, sd: E.E7.fit.sd },
    nextMan: E.E9.fit,
    wind: E.E10.fit.wind,
    health: E.E11.fit.health,
    signals: Object.fromEntries(['QB', 'RB', 'WR', 'TE'].map((pos) => [pos, E.E12.fit[pos].groups])),
    balance: E.E13.fit.balance,
    returns: E.E14.fit,
    picks: E.E15.fit.rounds,
    ranges: { ALL: E.E16.fit.ALL, posture: E.E16.fit.posture },
    firstBack: E.E14b.fit.factors,
    ecr: E.E8.fit.ecr,
    ros: { test: E.E19.fit.test, weight: E.E19.fit.weight },
    consensus: { early: E.E17.fit.early, closeCalls: E.E17.fit.test.WR.closeCalls },
    news: { before: E.N1.fit.before, heldoutFirst: E.N1.fit.heldoutFirst, freshFirst: E.N1.fit.freshFirst, fresh2First: E.N1.fit.fresh2First, freshN: E.N1.fit.freshN, dev: E.N1.fit.accuracy },
    now: pick(E),
    before: B ? pick(B) : null,
  };
  const js = `// Generated by backtest/run.mjs on ${out.generated}. Do not edit: run \`npm run backtest\`.\nexport const TRACK = ${JSON.stringify(track)};\n`;
  fs.writeFileSync(path.join(dir, '..', '..', 'public', 'js', 'track-data.js'), js);
  console.log('wrote public/js/track-data.js');
}
